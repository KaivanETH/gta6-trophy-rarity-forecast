"""tools/backtest.py -- score a candidate model the way the server scores an entry.

The metric is the competition's own: mean pinball loss over every trophy and level on
the logit scale, with the typical miss in percentage points and the 90% coverage the
board reports.  Lower loss is better; coverage should land near 0.90 and the miss
should stay small, because an honest wide band is cheap and a crossed tail is not.

Why this file was rewritten for round 3
---------------------------------------
Round 2's backtest said loss 0.0179 / miss 0.00 pp / coverage 1.000 while the server
said 0.159 / 0.05 / 0.4909 on the same program.  The folds were not kind, they were
circular: the "practice" truth was reconstructed with the same proportional transform
the model used to forecast, so the model was scored against its own assumption and the
two splits could only disagree with it where the rounding was ambiguous.  That is the
bug this file exists to fix.  A truth that is generated by the model cannot measure the
model.

So every family below takes its truth from data the model does not generate:

  trunc    Rolling origin on the kit's own recording.  A sub-case is cut at read j and
           asked for read k > j; truth is read k as recorded.  Honest but flat: on
           launch night the page does not move before the first republish, so this
           family only measures whether a design leaves a plateau alone.

  short    The same idea with the house trials' shapes: histories of 1, 3 or 6 reads
           instead of all of them, checkpoints in the last third of the recording, and
           reads with nulls punched out.  Short histories are where round 1's eleven
           trials of identical code spanned 0.157 to 1.6, so they are measured apart.

  refresh  The first republish, which is the only place the practice cases have a real
           answer.  The house published its aggregates -- 638 -> 3,868 tracked, 943 ->
           4,276 earned, every rate but the one at 100% lower -- but not how the 408
           non-100% earned counts split over the 54 trophies.  Any split with those
           totals is a legal answer, so this family draws many: integer counts whose
           expected value is proportional to the launch counts, with a lognormal
           per-trophy dispersion s, renormalised to the documented total.  s = 0 is the
           "each count grows by the same factor" split; larger s is a world where
           trophies move independently.  s is not chosen by taste: `calibrate` fits it
           to the server's own measurement of round 2 (coverage 0.4909, miss 0.05 pp,
           loss 0.159), because that measurement is the one observation we have of how
           far a real refreshed page sits from the proportional guess.

  world    Synthetic post-launch worlds for the final's shape (multi-day horizon, a
           moving history, republish plateaus): each trophy carries a persistent
           per-trophy offset with the dispersion the refresh family calibrated, so the
           world is not a smooth function of any fit.  Two variants: the final's shape
           (all reads, 4.5-day target) and the house trials' shape (last 6 reads only).

Every family scores the candidate, the round-2 model (loaded from a file, so the
comparison is the pushed code and not a memory of it) and the house persistence
baseline on the same folds.  A change is worth pushing only when it beats round 2 on
the aggregate and its coverage stays at or above 0.90 on every family.

Usage:
    python3 tools/backtest.py                 # every family, candidate vs round 2 vs base
    python3 tools/backtest.py calibrate       # fit the refresh dispersion to the board
    python3 tools/backtest.py refresh --draws 120
    python3 tools/backtest.py world  --worlds 12
    python3 tools/backtest.py trunc | short --input <kit input dir>
    --r2 <path to round-2 model.py>           # default /tmp/round2/model.py
"""

