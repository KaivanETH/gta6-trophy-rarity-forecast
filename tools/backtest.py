import random
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import model  # noqa: E402

LEVELS = model.LEVELS
Z = model.Z
RELEASE = datetime(2026, 11, 19, tzinfo=timezone.utc)
KIT_INPUT = Path('/root/.hermes/nft-hunter/makefun/'
                 'gta6-trophy-rarity-forecast-01-kit/input')
R2_DEFAULT = Path('/tmp/round2/model.py')

# The house's documented launch-night numbers, as the kit states them.
TRACKED_BEFORE = 638.0
EARNED_BEFORE = 943.0
TRACKED_AFTER = 3868.0
EARNED_AFTER = 4276.0

# What the live board said about round 2 on the dev phase (2026-11-21T06:06Z):
# 8730 ranked submissions, rank 1204, reasons ["coverage_below_gate"].
SERVER_R2 = {'loss': 0.159, 'miss': 0.05, 'coverage': 0.4909}


# ------------------------------------------------------------------------- scoring

def pinball(q, truth):
    """The competition's loss for one trophy: mean over the five levels."""
    zy = model.logit(truth)
    total = 0.0
    for tau, qv in zip(LEVELS, q):
        d = zy - model.logit(qv)
        total += 2.0 * max(tau * d, (tau - 1.0) * d)
    return total / len(LEVELS)


def score(rows, truths, ids):
    """loss, typical miss (pp), 90% coverage and the per-level hit rates."""
    by_id = {row['id']: row['q'] for row in rows}
    losses, misses = [], []
    covered = 0
    hits = [0] * len(LEVELS)
    for tid, truth in zip(ids, truths):
        if truth is None or tid not in by_id:
            continue
        q = by_id[tid]
        y = model.clamp_pct(truth)
        losses.append(pinball(q, truth))
        misses.append(abs(y - q[2]))
        covered += 1 if (q[0] <= y <= q[4]) else 0
        for k, qv in enumerate(q):
            hits[k] += 1 if qv <= y else 0
    n = len(losses)
    if not n:
        return {'loss': 0.0, 'miss': 0.0, 'coverage': 0.0,
                'levels': [0.0] * len(LEVELS), 'n': 0}
    return {'loss': sum(losses) / n, 'miss': sum(misses) / n,
            'coverage': covered / n, 'levels': [h / n for h in hits], 'n': n}


def combine(parts):
    """Pool per-fold scores into one row, weighted by the items each fold scored."""
    parts = [p for p in parts if p.get('n')]
    if not parts:
        return {'loss': 0.0, 'miss': 0.0, 'coverage': 0.0, 'levels': [0.0] * 5, 'n': 0}
    n = sum(p['n'] for p in parts)
    return {'loss': sum(p['loss'] * p['n'] for p in parts) / n,
            'miss': sum(p['miss'] * p['n'] for p in parts) / n,
            'coverage': sum(p['coverage'] * p['n'] for p in parts) / n,
            'levels': [sum(p['levels'][k] * p['n'] for p in parts) / n
                       for k in range(len(LEVELS))],
            'n': n,
            'worst_cov': min(p['coverage'] for p in parts)}


# ------------------------------------------------------------------------ baselines

def persistence_rows(case):
    """The house baseline, number for number: last read plus a random walk on the logit."""
    hist = case.get('history') or []
    rates = (hist[-1].get('rates') if hist else None) or []
    days = max(float(case.get('horizon_minutes') or 0.0), 0.0) / 1440.0
    spread = 0.5 * math.sqrt(days)
    rows = []
    for i, trophy in enumerate(case.get('trophies') or []):
        rate = rates[i] if i < len(rates) else None
        lg = model.logit(rate if rate is not None else 0.01)
        rows.append({'id': trophy.get('id', i + 1),
                     'q': [model.half_up(model.inv_logit(lg + z * spread)) for z in Z]})
    return rows


def load_round2(path):
    """Round 2's model.py, imported from a file so the comparison is the pushed code."""
    path = Path(path) if path else R2_DEFAULT
    if not path.exists():
        return None
    spec = importlib.util.spec_from_file_location('round2_model', str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def candidate_rows(case, params=None):
    return model.forecast_case(case, params)['trophies']


def rows_for(tag, case, r2, params=None):
    """The three rows every family reports: candidate, round 2, persistence."""
    out = {'cand': candidate_rows(case, params), 'base': persistence_rows(case)}
    if r2 is not None:
        try:
            out['r2'] = r2.forecast_case(case)['trophies']
        except Exception as exc:  # noqa: BLE001 - round 2 is a reference, not a dependency
            print('  round 2 raised on %s: %s' % (case.get('id'), exc))
    return out


# --------------------------------------------------------------------------- loading

def load_cases(directory):
    directory = Path(directory) if directory else KIT_INPUT
    paths = sorted(directory.glob('*.in'))
    if not paths:
        paths = sorted(KIT_INPUT.glob('*.in'))
    return [json.loads(p.read_text(encoding='utf-8')) for p in paths]


def iso(hours):
    return (RELEASE + timedelta(hours=hours)).strftime('%Y-%m-%dT%H:%M:%SZ')


def trophy_ids(case):
    return [t['id'] for t in case.get('trophies') or []]


def report(name, cand, r2row, base):
    """One line per family: every model on the same folds."""
    def fmt(prefix, row):
        if row is None:
            return ''
        return ' %s %.4f/cov %.3f' % (prefix, row['loss'], row['coverage'])
    cov = cand['coverage']
    flag = '' if cov >= 0.90 else '  <-- coverage under 0.90'
    if 'worst_cov' in cand and cand['worst_cov'] < 0.90:
        flag += ' (worst fold %.3f)' % cand['worst_cov']
    print('  %-10s cand %.4f%s%s  miss %6.3f pp  cov %.3f  n=%d%s'
          % (name, cand['loss'], fmt('r2', r2row), fmt('base', base),
             cand['miss'], cov, cand['n'], flag))


# ------------------------------------------------------------------ 1. truncations

def truncate(case, j, k, keep=None):
    """A sub-case whose history ends at read j and whose target is read k's stamp."""
    hist = case['history']
    sub = dict(case)
    sub['id'] = '%s@%d>%d' % (case.get('id'), j, k)
    sub['history'] = hist[:j + 1]
    if keep:
        sub['history'] = hist[max(0, j + 1 - keep):j + 1]
    sub['at'] = hist[j].get('at') or hist[j].get('slot')
    sub['target'] = hist[k].get('at') or hist[k].get('slot')
    sub['horizon_minutes'] = (model.parse_ts(sub['target'])
                              - model.parse_ts(sub['at'])) / 60.0
    return sub


def fold_trunc(cases, r2, params=None, keep=None, late_only=False, punch_holes=False):
    """All j < k truncations (optionally short histories, late checkpoints, nulls)."""
    parts = {'cand': [], 'r2': [], 'base': []}
    folds = 0
    for case in cases:
        hist = case.get('history') or []
        ids = trophy_ids(case)
        for k in range(1, len(hist)):
            truths = hist[k].get('rates')
            if not any(v is not None for v in truths or []):
                continue
            starts = range(k)
            if late_only:
                starts = range(max(0, (len(hist) * 2) // 3), k)
            for j in starts:
                sub = truncate(case, j, k, keep=keep)
                if punch_holes:
                    sub = dict(sub, history=hole_punch(sub['history']))
                rows = rows_for('trunc', sub, r2, params)
                parts['cand'].append(score(rows['cand'], truths, ids))
                parts['base'].append(score(rows['base'], truths, ids))
                if 'r2' in rows:
                    parts['r2'].append(score(rows['r2'], truths, ids))
                folds += 1
    out = {key: combine(vals) for key, vals in parts.items() if vals}
    out['folds'] = folds
    return out


def hole_punch(hist):
    """Drop every second read's odd trophies, the way a partial page read looks."""
    out = []
    for n, read in enumerate(hist):
        if n % 2 == 0:
            out.append(read)
            continue
        copy = dict(read)
        rates = list(read.get('rates') or [])
        copy['rates'] = [None if i % 2 else r for i, r in enumerate(rates)]
        out.append(copy)
    return out


# ---------------------------------------------------------------- 2. the republish

def refresh_truth(case, s, rng):
    """One legal answering page for the first republish, drawn at dispersion s.

    The documented totals are kept exactly: 3,868 tracked, 4,276 earned, the 100%
    trophy holding the whole tracked base.  The 408 remaining earned counts are split
    over the other trophies with expected value proportional to the launch counts; s is
    the lognormal per-trophy dispersion of that split, applied before renormalising to
    the documented total and rounding to whole counts.
    """
    rates = ((case.get('history') or [{}])[-1].get('rates')) or []
    counts = [max(0, int(round((r or 0.0) * TRACKED_BEFORE / 100.0))) for r in rates]
    full = [i for i, r in enumerate(rates) if (r or 0.0) >= model.PARAMS['full_pct']]
    others = [i for i in range(len(counts)) if i not in full]
    target = EARNED_AFTER - TRACKED_AFTER * len(full)
    weights = []
    for i in others:
        noise = math.exp(rng.gauss(-0.5 * s * s, s)) if s > 0.0 else 1.0
        weights.append(counts[i] * noise)
    total = sum(weights)
    if total <= 0.0:
        return [100.0 if i in full else 0.01 for i in range(len(counts))]
    exact = [target * w / total for w in weights]
    floors = [math.floor(v) for v in exact]
    need = int(round(target)) - sum(floors)
    order = sorted(range(len(others)), key=lambda k: -(exact[k] - floors[k]))
    alloc = dict(zip(others, floors))
    for k in order[:max(0, need)]:
        alloc[others[k]] += 1
    truths = []
    for i in range(len(counts)):
        got = TRACKED_AFTER if i in full else alloc.get(i, 0)
        truths.append(round(100.0 * got / TRACKED_AFTER, 2))
    return truths


def fold_refresh(cases, r2, s, draws, seed=11, params=None):
    """Score every model against `draws` legal answering pages per case."""
    rng = random.Random(seed)
    parts = {'cand': [], 'r2': [], 'base': []}
    worst = {'cand': 1.0, 'r2': 1.0}
    for case in cases:
        ids = trophy_ids(case)
        rows = rows_for('refresh', case, r2, params)
        for _ in range(draws):
            truths = refresh_truth(case, s, rng)
            for key in parts:
                if key in rows:
                    parts[key].append(score(rows[key], truths, ids))
    out = {}
    for key, vals in parts.items():
        if not vals:
            continue
        out[key] = combine(vals)
        out[key]['worst_cov'] = min(v['coverage'] for v in vals)
    out['draws'] = draws * len(cases)
    out['s'] = s
    return out


def calibrate(cases, r2, draws=200, seed=11):
    """Fit the refresh dispersion to the board's own measurement of round 2.

    Round 2's band was ~0.055 logits wide; the board says it covered 49% of the truths,
    missed by 0.05 pp and scored 0.159.  Those three numbers only happen together for
    one dispersion of the answering page, so find it: for each s, score round 2 against
    `draws` pages drawn at s, and pick the s whose (coverage, miss, loss) is closest to
    the board's.  Then report the candidate at that s -- that is the world round 2 was
    actually being graded in, and the family round 3 must be measured in.
    """
    if r2 is None:
        print('  need the round-2 model to calibrate (--r2 <path>)')
        return None
    target = SERVER_R2
    print('  board on round 2: loss %.4f  miss %.3f pp  cov %.4f'
          % (target['loss'], target['miss'], target['coverage']))
    print('  %-6s %-34s %-34s' % ('s', 'round 2 (loss / miss / cov)', 'distance'))
    best = None
    for s in (0.0, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.50):
        fold = fold_refresh(cases, r2, s, draws, seed)
        row = fold.get('r2')
        if row is None:
            return None
        dist = (math.log(max(row['coverage'], 1e-3) / target['coverage']) ** 2
                + (math.log(max(row['loss'], 1e-3) / target['loss'])) ** 2
                + ((row['miss'] - target['miss']) / 0.05) ** 2)
        print('  %-6.2f %.4f / %.3f / %.4f%18s %.4f'
              % (s, row['loss'], row['miss'], row['coverage'], '', dist))
        if best is None or dist < best[1]:
            best = (s, dist, row)
    s = best[0]
    print('  fitted dispersion s = %.2f logits (round 2 measured: %.4f / %.3f / %.4f)'
          % (s, best[2]['loss'], best[2]['miss'], best[2]['coverage']))
    return s


# ------------------------------------------------------------------- 3. synthetic worlds

class World:
    """A post-launch world: saturating curves, persistent per-trophy offsets, plateaus.

    Each trophy's logit rate is trend_i(hours) + offset_i, where trend_i is a saturating
    logistic in log time and offset_i is a *persistent* per-trophy deviation with the
    dispersion the refresh family calibrated -- the property that makes a real page's
    rates deviate from any tier trend for good, rather than by chance at each read.
    Players arrive in a step at the first republish and then grow to a ceiling; the page
    republishes every few hours, so reads inside a plateau are identical, and every rate
    is printed to two decimals.
    """

    def __init__(self, seed, trophies, seed_rates, dispersion=0.28, holes=False):
        rng = random.Random(seed)
        self.trophies = trophies
        self.n = len(trophies)
        self.holes = holes
        self.step_h = 4.55 + rng.uniform(-0.2, 0.2)
        self.cap_tracked = math.exp(rng.uniform(math.log(6e4), math.log(5e5)))
        self.tau_tracked = rng.uniform(30.0, 80.0)
        self.refresh = rng.choice((2.5, 3.5, 5.0))
        self.ceiling, self.gamma, self.alpha, self.offset = [], [], [], []
        for i, trophy in enumerate(trophies):
            rate = seed_rates[i] if i < len(seed_rates) and seed_rates[i] is not None else 1.0
            cap = {'bronze': 55.0, 'silver': 70.0, 'gold': 85.0,
                   'platinum': 99.0}.get(trophy.get('tier'), 55.0)
            cap = min(98.0, cap * math.exp(rng.uniform(-0.35, 0.35)))
            gamma = math.exp(rng.uniform(math.log(0.55), math.log(1.25)))
            offset = rng.gauss(0.0, dispersion)
            if rate >= 99.5:
                cap, gamma, offset = 100.0, 0.4, 0.0
            self.ceiling.append(cap)
            self.gamma.append(gamma)
            self.offset.append(offset)
            frac = min(0.98, max(0.002, rate / 100.0))
            self.alpha.append(math.log(frac / (1.0 - frac)) - gamma * math.log(2.5) - offset)
        self._page = {}

    def tracked(self, hours):
        if hours < self.step_h:
            return TRACKED_BEFORE
        return TRACKED_AFTER + (self.cap_tracked - TRACKED_AFTER) * (
            1.0 - math.exp(-(hours - self.step_h) / self.tau_tracked))

    def rates(self, hours):
        out = []
        for i in range(self.n):
            z = (self.alpha[i] + self.offset[i]
                 + self.gamma[i] * math.log1p(max(hours, 0.0)))
            out.append(self.ceiling[i] / (1.0 + math.exp(-z)))
        return out

    def stamp(self, hours):
        """The republish a read at `hours` shows: the page is static in between."""
        if hours < self.step_h:
            return 0.0
        return self.step_h + math.floor((hours - self.step_h) / self.refresh) * self.refresh

    def page(self, hours):
        key = round(self.stamp(hours), 6)
        if key not in self._page:
            self._page[key] = [round(r, 2) for r in self.rates(self.stamp(hours))]
        return list(self._page[key])

    def case(self, checkpoint_h, horizon_h, cadence_min, case_id='syn', keep=None):
        hist = []
        h = -0.17
        while h < checkpoint_h - 1e-9:
            rates = self.page(h)
            total = self.tracked(self.stamp(h))
            stamp = iso(h)
            slot = stamp
            if self.holes and len(hist) % 2 == 1:
                rates = [None if i % 2 else r for i, r in enumerate(rates)]
            hist.append({'slot': slot, 'at': stamp,
                         'players_tracked': int(round(total)),
                         'trophies_earned': int(round(sum(r for r in rates if r is not None)
                                                      * total / 100.0)),
                         'rates': rates})
            h += cadence_min / 60.0
        if keep:
            hist = hist[-keep:]
        return {'schema': 'makefun/gta6-trophies-case/v1', 'id': case_id,
                'at': iso(checkpoint_h),
                'target': iso(checkpoint_h + horizon_h),
                'horizon_minutes': horizon_h * 60.0, 'levels': list(LEVELS),
                'game': {'name': 'Grand Theft Auto VI', 'platform': 'PS5',
                         'release_date': '2026-11-19',
                         'source': 'https://www.exophase.com/game/'
                                   'grand-theft-auto-vi-psn/trophies/'},
                'trophies': self.trophies, 'history': hist, 'notes': 'synthetic'}


def fold_world(trophies, seed_rates, worlds=12, seed=7, params=None, dispersion=0.28,
               horizon=108.5, cadence=10.0, keep=None, holes=False, r2=None, tag='world',
               checkpoints=None, origin_shift=0.0):
    """The final's shape and the trials' shape, scored against the world's own page."""
    ids = trophy_ids({'trophies': trophies})
    parts = {'cand': [], 'r2': [], 'base': []}
    for w in range(worlds):
        world = World(seed + w, trophies, seed_rates, dispersion, holes)
        if checkpoints is not None:
            checkpoint = checkpoints[w % len(checkpoints)]
        else:
            checkpoint = 59.5 + (w % 5) * 1.3
            if origin_shift:
                world.step_h += origin_shift
        case = world.case(checkpoint, horizon, cadence, keep=keep)
        truth = world.page(checkpoint + horizon)
        rows = rows_for(tag, case, r2, params)
        for key in parts:
            if key in rows:
                parts[key].append(score(rows[key], truth, ids))
    out = {k: combine(v) for k, v in parts.items() if v}
    out['worst_cov'] = min(p['coverage'] for p in parts['cand']) if parts['cand'] else 0.0
    out['worlds'] = worlds
    return out


# ---------------------------------------------------------------------------- driver

def parse_sets(items):
    """--set key=value pairs, numbers where they look like numbers."""
    out = {}
    for item in items:
        key, _, value = item.partition('=')
        try:
            out[key.strip()] = float(value)
        except ValueError:
            out[key.strip()] = value
    return out

def run_all(args):
    cases = load_cases(args.input)
    r2 = load_round2(args.r2)
    if r2 is None:
        print('note: no round-2 model at %s; comparisons skip that column' % (args.r2 or
                                                                              R2_DEFAULT,))
    overrides = parse_sets(args.set)
    print('== truncation folds: every j < k on the kit recording ==')
    t = fold_trunc(cases, r2, overrides)
    report('trunc', t['cand'], t.get('r2'), t.get('base'))
    print('== short-history folds: 3 reads, late checkpoints, nulls punched out ==')
    sh = fold_trunc(cases, r2, overrides, keep=3, late_only=True, punch_holes=True)
    report('short', sh['cand'], sh.get('r2'), sh.get('base'))

    print('== refresh folds: legal answering pages at the calibrated dispersion ==')
    s = calibrate(cases, r2, args.draws)
    if s is not None:
        for probe in (0.0, s):
            fold = fold_refresh(cases, r2, probe, args.draws, params=overrides)
            report('refresh/%.2f' % probe, fold['cand'], fold.get('r2'), fold.get('base'))
            if fold.get('r2'):
                print('  %-10s round 2 %.4f  miss %6.3f pp  cov %.3f (worst %.3f)'
                      % ('', fold['r2']['loss'], fold['r2']['miss'],
                         fold['r2']['coverage'], fold['r2']['worst_cov']))

    seed_rates = (cases[0].get('history') or [{}])[-1].get('rates')
    trophies = cases[0]['trophies']
    print('== synthetic worlds: final shape (all reads, 4.5-day target) ==')
    wd = fold_world(trophies, seed_rates, args.worlds, args.seed, r2=r2, tag='world', params=overrides)
    report('world', wd['cand'], wd.get('r2'), wd.get('base'))
    print('== synthetic worlds: trials shape (short histories, 90-minute target) ==')
    for keep in (3, 6):
        wd2 = fold_world(trophies, seed_rates, args.worlds, args.seed, r2=r2,
                         horizon=1.5, cadence=10.0, keep=keep, holes=True,
                         checkpoints=(14.0, 26.0, 38.0, 52.0), tag='trial', params=overrides)
        report('trial/%-2s' % keep, wd2['cand'], wd2.get('r2'), wd2.get('base'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('what', nargs='?', default='all',
                    choices=('all', 'trunc', 'short', 'refresh', 'world', 'trial', 'calibrate'))
    ap.add_argument('--input', default=None)
    ap.add_argument('--r2', default=None)
    ap.add_argument('--draws', type=int, default=120)
    ap.add_argument('--worlds', type=int, default=12)
    ap.add_argument('--seed', type=int, default=7)
    ap.add_argument('--s', type=float, default=None, help='refresh dispersion to use')
    ap.add_argument('--set', action='append', default=[],
                    help='override a model PARAMS key, e.g. --set trend_mix=0.75')
    args = ap.parse_args()
    overrides = parse_sets(args.set)
    if overrides:
        print('overrides: %r' % (overrides,))
    cases = load_cases(args.input)
    r2 = load_round2(args.r2)

    if args.what == 'all':
        run_all(args)
        return
    if args.what == 'calibrate':
        calibrate(cases, r2, args.draws)
        return
    if args.what == 'trunc':
        t = fold_trunc(cases, r2, overrides)
        report('trunc', t['cand'], t.get('r2'), t.get('base'))
    elif args.what == 'short':
        t = fold_trunc(cases, r2, overrides, keep=3, late_only=True, punch_holes=True)
        report('short', t['cand'], t.get('r2'), t.get('base'))
    elif args.what == 'refresh':
        s = args.s if args.s is not None else calibrate(cases, r2, args.draws)
        if s is None:
            return
        fold = fold_refresh(cases, r2, s, args.draws, params=overrides)
        report('refresh/%.2f' % s, fold['cand'], fold.get('r2'), fold.get('base'))
    elif args.what == 'trial':
        seed_rates = (cases[0].get('history') or [{}])[-1].get('rates')
        trophies = cases[0]['trophies']
        for keep in (3, 6, None):
            wd = fold_world(trophies, seed_rates, args.worlds, args.seed, r2=r2,
                            horizon=1.5, cadence=10.0, keep=keep, holes=True,
                            checkpoints=(14.0, 26.0, 38.0, 52.0), dispersion=args.s or 0.30)
            report('trial/%-4s' % (keep or 'all'), wd['cand'], wd.get('r2'), wd.get('base'))
    elif args.what == 'world':
        seed_rates = (cases[0].get('history') or [{}])[-1].get('rates')
        trophies = cases[0]['trophies']
        wd = fold_world(trophies, seed_rates, args.worlds, args.seed, r2=r2, params=overrides)
        report('world', wd['cand'], wd.get('r2'), wd.get('base'))
        wd2 = fold_world(trophies, seed_rates, args.worlds, args.seed, r2=r2,
                         keep=6, holes=True, params=overrides)
        report('world-short', wd2['cand'], wd2.get('r2'), wd2.get('base'))


if __name__ == '__main__':
    main()
